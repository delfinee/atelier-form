"""Portable Windows/macOS/Linux entry point. No credentials are bundled."""
import argparse
import json
import os
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
import venv

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--phone', action='store_true')
    parser.add_argument('--storefront', action='store_true')
    parser.add_argument('--origin', help='Approved HTTPS origin for real WeChat')
    parser.add_argument('--env-file', type=Path)
    parser.add_argument('--setup-only', action='store_true')
    args = parser.parse_args()
    if args.env_file and not args.env_file.is_file():
        parser.error('The requested --env-file does not exist.')
    os.chdir(ROOT)
    os.environ['PYTHONUTF8'] = '1'
    existing = ROOT.parent / 'dip-new-repo-test' / '.env'
    env = args.env_file or (ROOT / '.env' if (ROOT / '.env').exists() else existing)
    managed_database = False
    if not env.is_file():
        env = ROOT / '.env'
        password = secrets.token_hex(24)
        env.write_text('# Generated by launch_seller.py for Docker demo\nAPP_ENV=development\nDJANGO_DEBUG=1\nDJANGO_SECRET_KEY=' + secrets.token_urlsafe(50)
            + '\nDATABASE_URL=postgres://atelier:' + password + '@127.0.0.1:55433/atelier_form\n'
            + 'POSTGRES_PASSWORD=' + password + '\nSELLER_AGENT_USE_LLM=0\n', encoding='utf-8')
        managed_database = True
        print('Created private .env for the local demo database. Do not share this file.', flush=True)
    # A generated demo env is also recognised on subsequent starts.
    if '# Generated by launch_seller.py for Docker demo' in env.read_text(encoding='utf-8'):
        managed_database = True
    if managed_database:
        if not shutil.which('docker'):
            raise SystemExit('Install/start Docker Desktop and run this launcher again, or supply --env-file for an existing PostgreSQL database. See TEAM_ACCEPTANCE.md.')
        subprocess.run(['docker', 'compose', '--env-file', str(env), '-f', 'compose.seller-demo.yml',
                        'up', '-d', '--wait'], check=True)
    sibling = ROOT.parent / 'runtime' / 'venv' / 'Scripts' / 'python.exe'
    local = ROOT / '.venv' / ('Scripts/python.exe' if os.name == 'nt' else 'bin/python')
    python = sibling if env == existing and sibling.exists() else local
    if not python.exists():
        if sys.version_info < (3, 11):
            raise SystemExit('Python 3.11 or later is required.')
        print('Creating a project-local Python environment...', flush=True)
        venv.EnvBuilder(with_pip=True).create(ROOT / '.venv')
        subprocess.run([str(local), '-m', 'pip', 'install', '-r', 'requirements.txt'], check=True)
        python = local
    os.environ['DIP_ENV_FILE'] = str(env.resolve())
    os.environ['DJANGO_SETTINGS_MODULE'] = 'config.seller_agent_local'
    subprocess.run([str(python), 'manage.py', 'migrate', '--noinput'], check=True)
    if args.storefront:
        subprocess.run([str(python), 'manage.py', 'prepare_marketplace'], check=True)
    subprocess.run([str(python), 'manage.py', 'seed_seller_acceptance'], check=True)
    if args.setup_only:
        print('Setup complete. Run START-SELLER-WECHAT.cmd to open the local seller site.')
        return
    if args.phone:
        origin = args.origin
        state = ROOT / '.seller-agent-runtime' / 'phone-preview.json'
        if not origin and state.exists():
            origin = json.loads(state.read_text(encoding='utf-8'))['origin']
        if not origin:
            raise SystemExit('Use --phone --origin https://YOUR-APPROVED-DOMAIN. See SELLER_PHONE.md.')
        command = ['run_seller_phone.py', '--origin', origin]
    else:
        command = ['run_seller_agent.py']
        if args.storefront:
            command.append('--storefront')
    subprocess.run([str(python), *command, '--env-file', str(env)], check=True)


if __name__ == '__main__':
    try:
        main()
    except subprocess.CalledProcessError as exc:
        raise SystemExit('Setup/start command failed (exit ' + str(exc.returncode) + '). Review the message above; no project data was deleted.') from None
